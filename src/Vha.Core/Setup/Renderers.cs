    /// <summary>Everything that derives from the configuration for one availability group on one node.</summary>
    public static class NodeNaming
    {
        /// <summary>SQL Server address of the local instance as the service and CsuCmd.exe use it: dns\instance, or dns,port.</summary>
        public static string SqlAddress(NodeSettings node, AgSettings ag)
        {
            if (ag.SqlPort > 0) return node.DnsName + "," + ag.SqlPort.ToString(CultureInfo.InvariantCulture);
            return string.IsNullOrEmpty(ag.InstanceName) ? node.DnsName : node.DnsName + "\\" + ag.InstanceName;
        }

        /// <summary>Folder of one AG on a node: &lt;install&gt;\&lt;instance|default&gt;\&lt;AG&gt;</summary>
        public static string AgDirectory(DeploymentConfig c, AgSettings ag) =>
            c.InstallDirectory.TrimEnd('\\') + "\\" + (string.IsNullOrEmpty(ag.InstanceName) ? "default" : ag.InstanceName) + "\\" + ag.Name;
    }

    public static class IniRenderer
    {
        /// <summary>jelena.ini read by ClusteredService.exe (round-trip tested against <see cref="Vha.Core.Config.ServiceSettings"/>).</summary>
        public static string Render(DeploymentConfig c, AgSettings ag, NodeSettings node)
        {
            var sb = new StringBuilder();
            sb.AppendLine("; Generated by vHA Setup - edit the deployment file and run the setup again instead of editing this file.");
            sb.AppendLine("[General]");
            sb.AppendLine("LogRetentionDays=31");
            sb.AppendLine();
            sb.AppendLine("[VIM]");
            sb.AppendLine("VirtualMachineName=" + node.VmName);
            sb.AppendLine();
            sb.AppendLine("[AG]");
            sb.AppendLine("AGName=" + ag.Name);
            sb.AppendLine(ag.ServiceName + "=" + ag.Name);
            sb.AppendLine("Instance=" + NodeNaming.SqlAddress(node, ag));
            sb.AppendLine("Reservation=" + (ag.ReservationEnabled ? "Y" : "N"));
            sb.AppendLine("TaskName=" + ag.EffectiveTaskName);
            if (!string.IsNullOrWhiteSpace(ag.SqlOptions)) sb.AppendLine("SqlOptions=" + ag.SqlOptions.Trim());
            sb.AppendLine();
            sb.AppendLine("[Failover]");
            sb.AppendLine("OwnerUnreachablePolicy=" + ag.OwnerUnreachablePolicy);
            sb.AppendLine("CsuWaitSeconds=" + ag.CsuWaitSeconds.ToString(CultureInfo.InvariantCulture));
            sb.AppendLine("FailoverTimeoutSeconds=" + ag.FailoverTimeoutSeconds.ToString(CultureInfo.InvariantCulture));
            return sb.ToString().Replace("\r\n", "\n").Replace("\n", "\r\n");
        }

        /// <summary>&lt;mount&gt;\jelena\disksign.ini</summary>
        public static string DiskSign(AgSettings ag) => "[AG]\r\nName=" + ag.Name + "\r\n";
    }

    public static class TaskXmlRenderer
    {
        private static readonly XNamespace Ns = "http://schemas.microsoft.com/windows/2004/02/mit/task";

        /// <summary>
        /// Task Scheduler XML (schema 1.2, Windows Server 2016-2025) for CsuCmd.exe. The start second is staggered by AG index
        /// (0, 15, 30, 45...) as the installation guide asks, so tasks of different AGs do not start in the same second.
        /// </summary>
        public static string Render(DeploymentConfig c, int agIndex, NodeSettings node)
        {
            var ag = c.AvailabilityGroups[agIndex];
            var second = (agIndex * 15) % 60;
            var args = string.Join(" ", new[] { node.VmName, ag.Name, NodeNaming.SqlAddress(node, ag) }.Select(ProcessArgs.Quote)) + " " + ag.CsuLogLevel.ToString(CultureInfo.InvariantCulture);
            var exe = c.InstallDirectory.TrimEnd('\\') + "\\CsuCmd.exe";
            var minutes = ag.CsuIntervalSeconds / 60;

            var doc = new XDocument(
                new XElement(Ns + "Task", new XAttribute("version", "1.2"),
                    new XElement(Ns + "RegistrationInfo",
                        new XElement(Ns + "Description", "vHA continuous update (CSU) for availability group " + ag.Name),
                        new XElement(Ns + "Author", "vHA Setup")),
                    new XElement(Ns + "Triggers",
                        new XElement(Ns + "TimeTrigger",
                            new XElement(Ns + "Repetition",
                                new XElement(Ns + "Interval", "PT" + minutes.ToString(CultureInfo.InvariantCulture) + "M"),
                                new XElement(Ns + "StopAtDurationEnd", "false")),
                            new XElement(Ns + "StartBoundary", "2026-01-01T00:00:" + second.ToString("00", CultureInfo.InvariantCulture)),
                            new XElement(Ns + "Enabled", "true"))),
                    new XElement(Ns + "Principals",
                        new XElement(Ns + "Principal", new XAttribute("id", "Author"),
                            new XElement(Ns + "UserId", c.TaskAccount.Trim()),
                            new XElement(Ns + "LogonType", "Password"),
                            new XElement(Ns + "RunLevel", "HighestAvailable"))),
                    new XElement(Ns + "Settings",
                        new XElement(Ns + "MultipleInstancesPolicy", "IgnoreNew"),
                        new XElement(Ns + "DisallowStartIfOnBatteries", "false"),
                        new XElement(Ns + "StopIfGoingOnBatteries", "false"),
                        new XElement(Ns + "AllowHardTerminate", "true"),
                        new XElement(Ns + "StartWhenAvailable", "true"),
                        new XElement(Ns + "RunOnlyIfNetworkAvailable", "false"),
                        new XElement(Ns + "AllowStartOnDemand", "true"),
                        new XElement(Ns + "Enabled", "true"),
                        new XElement(Ns + "Hidden", "false"),
                        new XElement(Ns + "RunOnlyIfIdle", "false"),
                        new XElement(Ns + "WakeToRun", "false"),
                        new XElement(Ns + "ExecutionTimeLimit", "PT30M"),
                        new XElement(Ns + "Priority", "7")),
                    new XElement(Ns + "Actions", new XAttribute("Context", "Author"),
                        new XElement(Ns + "Exec",
                            new XElement(Ns + "Command", exe),
                            new XElement(Ns + "Arguments", args),
                            new XElement(Ns + "WorkingDirectory", c.InstallDirectory.TrimEnd('\\'))))));
            return "<?xml version=\"1.0\" encoding=\"UTF-16\"?>\r\n" + doc.ToString();
        }
    }

    /// <summary>Textual $(Var) substitution for the sql/*.sql scripts (what sqlcmd -v does), safe for values used inside string literals.</summary>
    public static class SqlScriptTemplate
    {
        private static readonly Regex VarRx = new Regex(@"\$\(([A-Za-z_][A-Za-z0-9_]*)\)", RegexOptions.Compiled);
        private static readonly HashSet<string> Numeric = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "CpuMHz", "MemMB" };

        public static string Apply(string script, IDictionary<string, string> vars)
        {
            return VarRx.Replace(script, m =>
            {
                var name = m.Groups[1].Value;
                string value;
                if (!vars.TryGetValue(name, out value))
                {
                    var key = vars.Keys.FirstOrDefault(k => string.Equals(k, name, StringComparison.OrdinalIgnoreCase));
                    if (key == null) throw new InvalidOperationException("Script variable $(" + name + ") has no value");
                    value = vars[key];
                }
                value = value ?? "";
                if (value.IndexOf('\0') >= 0) throw new ArgumentException("Value of " + name + " contains NUL");
                if (Numeric.Contains(name))
                {
                    if (!Regex.IsMatch(value, @"^[0-9]{1,9}$")) throw new ArgumentException("Value of " + name + " must be a non-negative integer");
                    return value;
                }
                return value.Replace("'", "''");
            });
        }

        /// <summary>Splits a script at GO lines (the batch separator of sqlcmd/SSMS).</summary>
        public static IEnumerable<string> Batches(string script) =>
            Regex.Split(script, @"^\s*GO\s*$", RegexOptions.Multiline | RegexOptions.IgnoreCase).Where(b => !string.IsNullOrWhiteSpace(b));
    }

    /// <summary>Adds an account to a "User Rights Assignment" line of a secedit INF export.</summary>
    public static class UserRightsInf
    {
        public static bool Contains(string inf, string right, string sid)
        {
            var line = FindLine(inf, right);
            return line != null && line.IndexOf("*" + sid, StringComparison.OrdinalIgnoreCase) >= 0;
        }

        public static string AddAccount(string inf, string right, string sid)
        {
            if (!Regex.IsMatch(right, @"^Se[A-Za-z]+$")) throw new ArgumentException("Invalid right name", nameof(right));
            if (!Regex.IsMatch(sid, @"^S-1-[0-9]+(-[0-9]+)+$")) throw new ArgumentException("Invalid SID", nameof(sid));
            var lines = inf.Replace("\r\n", "\n").Split('\n').ToList();
            for (int i = 0; i < lines.Count; i++)
            {
                if (!IsRightLine(lines[i], right)) continue;
                if (lines[i].IndexOf("*" + sid, StringComparison.OrdinalIgnoreCase) >= 0) return inf;
                var value = lines[i].Substring(lines[i].IndexOf('=') + 1).Trim();
                lines[i] = right + " = " + (value.Length == 0 ? "*" + sid : value + ",*" + sid);
                return string.Join("\r\n", lines);
            }
            var header = lines.FindIndex(l => l.Trim().Equals("[Privilege Rights]", StringComparison.OrdinalIgnoreCase));
            if (header < 0) { lines.Add("[Privilege Rights]"); header = lines.Count - 1; }
            lines.Insert(header + 1, right + " = *" + sid);
            return string.Join("\r\n", lines);
        }

        private static string FindLine(string inf, string right) => inf.Replace("\r\n", "\n").Split('\n').FirstOrDefault(l => IsRightLine(l, right));
        private static bool IsRightLine(string line, string right)
        {
            var t = line.TrimStart();
            if (!t.StartsWith(right, StringComparison.OrdinalIgnoreCase)) return false;
            var rest = t.Substring(right.Length).TrimStart();
            return rest.StartsWith("=", StringComparison.Ordinal);
        }
    }
